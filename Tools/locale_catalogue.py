"""Write Locales/enUS.lua: the catalogue of every player-facing key (GG-403).

Scans the TOC's Lua files (not Locales/ or Core/Locale.lua) for GG.L lookups
written as L["..."] (double quotes, a literal key), decodes the Lua escapes,
and writes each key once, grouped by the first file that uses it, in file
order. tests/test_locale.lua checks the result matches the code.

    python -I Tools/locale_catalogue.py          (from the repo root)
    python -I Tools/locale_catalogue.py --check  (exit 1 if out of date)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BS = chr(92)
ESC = {"n": "\n", "t": "\t", "r": "\r", "a": "\a", "b": "\b", "f": "\f", "v": "\v",
       BS: BS, '"': '"', "'": "'"}


def toc_files():
    out = []
    with open(os.path.join(ROOT, "GlassGear.toc"), encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#") or not line.endswith(".lua"):
                continue
            rel = line.replace(BS, "/")
            if rel.startswith("Locales/") or rel == "Core/Locale.lua" or rel.startswith("Libs/"):
                continue
            out.append(rel)
    return out


def decode(raw):
    """Lua short-string escapes -> bytes."""
    out = bytearray()
    i = 0
    while i < len(raw):
        c = raw[i]
        if c != BS:
            out += c.encode("utf-8")
            i += 1
            continue
        n = raw[i + 1]
        if n.isdigit():
            j = i + 1
            while j < len(raw) and j < i + 4 and raw[j].isdigit():
                j += 1
            out.append(int(raw[i + 1:j]))
            i = j
        else:
            out += ESC[n].encode("utf-8")
            i += 2
    return bytes(out)


def keys_in(text):
    """Every L["..."] literal key in a Lua source, in order (bytes)."""
    found = []
    i = 0
    marker = 'L["'
    while True:
        i = text.find(marker, i)
        if i < 0:
            return found
        # GG.L["..."] or a bare L["..."]: the character before is not part of a name.
        prev = text[i - 1] if i > 0 else " "
        if prev.isalnum() or prev == "_":
            i += len(marker)
            continue
        j = i + len(marker)
        raw = []
        while text[j] != '"':
            if text[j] == BS:
                raw.append(text[j:j + 2])
                if text[j + 1].isdigit():
                    k = j + 1
                    while k < j + 4 and text[k].isdigit():
                        k += 1
                    raw[-1] = text[j:k]
                    j = k
                    continue
                j += 2
            else:
                raw.append(text[j])
                j += 1
        if text[j + 1] == "]":
            found.append(decode("".join(raw)))
        i = j + 1


def encode(key):
    """bytes -> a Lua double-quoted literal body (ASCII, decimal escapes)."""
    out = []
    for b in key:
        ch = chr(b)
        if ch == '"':
            out.append(BS + '"')
        elif ch == BS:
            out.append(BS + BS)
        elif ch == "\n":
            out.append(BS + "n")
        elif 32 <= b < 127:
            out.append(ch)
        else:
            out.append(BS + str(b))
    return "".join(out)


def build():
    seen = set()
    lines = [
        "------------------------------------------------------------",
        "-- Locales/enUS.lua - every player-facing key (GG-403), generated by",
        "-- Tools/locale_catalogue.py from the code's L[\"...\"] lookups. Not loaded:",
        "-- English is the keys themselves. A translation copies the keys it",
        "-- translates into Locales/<locale>.lua:",
        "--",
        "--     GlassGear.Locale.Register(\"deDE\", {",
        "--         [\"Not an upgrade for %s\"] = \"Kein Upgrade f\\195\\188r %s\",",
        "--     })",
        "--",
        "-- and lists that file in the TOC right after Core\\Locale.lua. Keep each",
        "-- %-specifier (%s, %d, %.1f...) in the same order: a translation that",
        "-- changes them is ignored.",
        "------------------------------------------------------------",
        "",
        "return {",
    ]
    for rel in toc_files():
        with open(os.path.join(ROOT, rel), encoding="utf-8") as f:
            text = f.read()
        new = [k for k in keys_in(text) if k not in seen]
        uniq = []
        for k in new:
            if k not in seen:
                seen.add(k)
                uniq.append(k)
        if uniq:
            lines.append("    -- " + rel)
            for k in uniq:
                lines.append('    "' + encode(k) + '",')
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    path = os.path.join(ROOT, "Locales", "enUS.lua")
    text = build()
    if "--check" in sys.argv:
        try:
            with open(path, encoding="utf-8") as f:
                current = f.read().replace("\r\n", "\n")
        except FileNotFoundError:
            current = ""
        if current != text:
            print("Locales/enUS.lua is out of date: run python -I Tools/locale_catalogue.py")
            sys.exit(1)
        print("Locales/enUS.lua is up to date")
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", path, text.count('",\n'), "keys")


if __name__ == "__main__":
    main()
