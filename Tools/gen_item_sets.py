"""Generate Data/ItemSets.lua from the client's ItemSet and ItemSetSpell tables (GG-119).

Reads the newest saved CSVs in References/Forever/db (fetched with the shared
wago-tools skill: `python References/Tools/Wago/wago.py get ItemSet ItemSetSpell`);
never the site. Writes, per set ID, the piece counts at which a bonus starts:

    [setID] = { 2, 4 }

A set the client lists without any bonus spell gets `{}`: known, no bonus.

Usage: python -I Tools/gen_item_sets.py [--db <References/Forever/db>] [--out Data/ItemSets.lua]
"""

import argparse
import csv
import glob
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
DEFAULT_DB = os.path.normpath(os.path.join(REPO, "..", "References", "Forever", "db"))


def newest(db, table):
    """The newest build's CSV of a table: (path, build)."""
    best = None
    for path in glob.glob(os.path.join(db, f"forever-{table}-*.csv")):
        m = re.search(r"-(\d+)\.(\d+)\.(\d+)\.(\d+)\.csv$", path)
        if not m:
            continue
        key = tuple(int(x) for x in m.groups())
        if best is None or key > best[0]:
            best = (key, path)
    if best is None:
        sys.exit(f"no forever-{table}-<build>.csv in {db}: fetch it with wago.py get first")
    return best[1], ".".join(str(x) for x in best[0])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--db", default=DEFAULT_DB)
    ap.add_argument("--out", default=os.path.join(REPO, "Data", "ItemSets.lua"))
    args = ap.parse_args()

    set_path, set_build = newest(args.db, "itemset")
    spell_path, spell_build = newest(args.db, "itemsetspell")
    if set_build != spell_build:
        sys.exit(f"ItemSet is {set_build} but ItemSetSpell is {spell_build}: fetch both at one build")

    sets = {}
    with open(set_path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            sets[int(row["ID"])] = set()
    unknown = 0
    with open(spell_path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            set_id, threshold = int(row["ItemSetID"]), int(row["Threshold"])
            if set_id not in sets:
                unknown += 1        # a bonus row for a set the client doesn't list: skip
                continue
            if threshold > 0:
                sets[set_id].add(threshold)

    lines = [
        "------------------------------------------------------------",
        "-- Data/ItemSets.lua - set-bonus thresholds: [setID] = { pieces, ... }.",
        "--",
        f"-- GENERATED by Tools/gen_item_sets.py from the client's ItemSet and",
        f"-- ItemSetSpell tables, build {set_build} (References/Forever/db, wago.tools).",
        "-- Do not edit by hand: re-fetch the tables for a new build and re-run it.",
        "-- {} = a set with no bonus. A setID missing here (a newer set) reports",
        "-- SET_BONUS_NOT_SCORED, never a silent zero.",
        "------------------------------------------------------------",
        "",
        "local GG = GlassGear",
        f'GG.Data.ItemSetsBuild = "{set_build}"',
        "GG.Data.ItemSets = {",
    ]
    for set_id in sorted(sets):
        pieces = ", ".join(str(n) for n in sorted(sets[set_id]))
        lines.append(f"    [{set_id}] = {{ {pieces} }}," if pieces else f"    [{set_id}] = {{}},")
    lines.append("}")
    lines.append("")
    with open(args.out, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines))
    with_bonus = sum(1 for s in sets.values() if s)
    print(f"{args.out}: {len(sets)} sets ({with_bonus} with bonuses), build {set_build}"
          + (f", {unknown} bonus rows for unlisted sets skipped" if unknown else ""))


if __name__ == "__main__":
    main()
